"""Export beat grid, drum hits and stem envelopes to ../video/src/audio_data.js"""
import numpy as np, librosa, json
SR=22050
raw = json.load(open('beats_raw.json'))
T0, SPB = 0.14, 0.6
# fit grid to detected beats (least squares) for sub-ms accuracy
b = np.array(raw['beats']); n = np.round((b - T0)/SPB)
A = np.vstack([np.ones_like(n), n]).T
t0, spb = np.linalg.lstsq(A, b, rcond=None)[0]
print("fitted grid t0=%.4f spb=%.5f bpm=%.3f resid=%.4f" % (t0, spb, 60/spb, np.abs(A@[t0,spb]-b).max()))

def band_onsets(y, fmin, fmax, delta, wait=4):
    S = np.abs(librosa.stft(y, n_fft=2048, hop_length=256))
    f = librosa.fft_frequencies(sr=SR, n_fft=2048)
    Sb = S[(f>=fmin)&(f<fmax)]
    env = librosa.onset.onset_strength(S=librosa.amplitude_to_db(Sb, ref=np.max), sr=SR, hop_length=256)
    on = librosa.onset.onset_detect(onset_envelope=env, sr=SR, hop_length=256, units='time', delta=delta, wait=wait, backtrack=False)
    # strength at onset
    fr = librosa.time_to_frames(on, sr=SR, hop_length=256)
    rms = np.sqrt((Sb**2).mean(axis=0)) / 1024
    lv = librosa.amplitude_to_db(rms, ref=1.0)
    return [(round(float(t),3), round(float(lv[min(i+2,len(lv)-1)]),1)) for t,i in zip(on,fr)]

yd,_ = librosa.load('stems/htdemucs/song/drums.wav', sr=SR, mono=True)
kicks = [k for k in band_onsets(yd, 20, 150, 0.25) if k[1] > -25]
snares = [k for k in band_onsets(yd, 1500, 5000, 0.25) if k[1] > -72]
hats = [k for k in band_onsets(yd, 7000, 11000, 0.2, 2) if k[1] > -82]
print("kicks", len(kicks), kicks[:12])
print("snares", len(snares), snares[:12])
print("hats", len(hats))
yo,_ = librosa.load('stems/htdemucs/song/other.wav', sr=SR, mono=True)
oenv = librosa.onset.onset_strength(y=yo, sr=SR, hop_length=256)
gon = librosa.onset.onset_detect(onset_envelope=oenv, sr=SR, hop_length=256, units='time', delta=0.3)
print("guitar onsets", len(gon))

# envelopes at 50 Hz normalized 0..1 (per stem, db-mapped)
HOP = SR//50
env = {}
for nm in ['vocals','drums','bass','other']:
    y,_ = librosa.load(f'stems/htdemucs/song/{nm}.wav', sr=SR, mono=True)
    r = librosa.feature.rms(y=y, frame_length=HOP*2, hop_length=HOP)[0]
    db = librosa.amplitude_to_db(r, ref=1.0)
    v = np.clip((db + 50)/40, 0, 1)   # -50dB -> 0, -10dB -> 1
    env[nm] = [int(x*99) for x in v]
ym,_ = librosa.load('song.wav', sr=SR, mono=True)
r = librosa.feature.rms(y=ym, frame_length=HOP*2, hop_length=HOP)[0]
db = librosa.amplitude_to_db(r, ref=1.0)
env['mix'] = [int(x*99) for x in np.clip((db+40)/35,0,1)]

vocal_regions = [(9.12,10.82),(11.2,11.62),(12.1,12.42),(13.58,14.1),(15.0,15.54),(28.98,35.52),(55.6,58.34),(61.34,64.62),(65.78,69.02),(96.1,111.72)]
data = dict(
  duration=128.0, t0=round(float(t0),4), spb=round(float(spb),5), bpm=round(float(60/spb),3), beatsPerBar=4,
  beats=[round(x,3) for x in raw['beats']], downbeats=[round(x,3) for x in raw['downbeats']],
  kicks=[k[0] for k in kicks], snares=[s[0] for s in snares], hats=[h[0] for h in hats],
  guitar=[round(float(x),3) for x in gon],
  vocalRegions=vocal_regions,
  envRate=50, env=env,
)
import os
os.makedirs('../video/src', exist_ok=True)
with open('../video/src/audio_data.js','w') as f:
    f.write('// Generated by analysis/export_timing.py — do not edit by hand.\n')
    f.write('export const AUDIO = ' + json.dumps(data, separators=(',',':')) + ';\n')
print("wrote", os.path.getsize('../video/src/audio_data.js'), "bytes")
